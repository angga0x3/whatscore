package signal

// Sender keys: the group ratchet. A group message is not encrypted per
// recipient device with X3DH; each member distributes one SenderKey (a chain
// key plus a signing key) to the others, then encrypts every message once
// with a key derived from that chain and signs it.
//
// The wire formats are libsignal's protobuf messages with a version byte in
// the high nibble (PF-093):
//
//	SenderKeyDistributionMessage: version || {id=1, iteration=2, chainKey=3, signingKey=4}
//	SenderKeyMessage:             version || {id=1, iteration=2, ciphertext=3} || signature(64)
//
// The chain derives one message key per iteration:
//
//	messageSeed = HMAC-SHA256(chainKey, 0x01)
//	iv(16) || cipherKey(32) = HKDF(sha256, messageSeed, salt=nil, info="WhisperGroup", 48)
//	nextChainKey = HMAC-SHA256(chainKey, 0x02)
//
// The signature is XEdDSA over the version byte and the protobuf body, under
// the signing key the distribution message named. Vectors in the test are
// generated by go.mau.fi/libsignal v0.2.2, the reference the project already
// validates its other Signal primitives against.

import (
	"crypto/hkdf"
	"crypto/hmac"
	"crypto/sha256"
	"errors"
	"fmt"

	"github.com/angga0x3/whatscore/internal/cbc"
	"github.com/angga0x3/whatscore/internal/xeddsa"
)

const (
	// SenderKeyInfo is the HKDF info string for a sender message key.
	SenderKeyInfo = "WhisperGroup"
	// SenderKeyMessageSeed derives the message key from the chain key.
	SenderKeyMessageSeed = 0x01
	// SenderKeyChainSeed derives the next chain key.
	SenderKeyChainSeed = 0x02
	// SenderKeySignatureSize is the XEdDSA signature length.
	SenderKeySignatureSize = 64
	// MaxSenderKeyAdvance bounds how far a received iteration may run ahead
	// of the stored chain. libsignal uses 2000; a larger gap is refused
	// rather than making the receiver derive keys without limit.
	MaxSenderKeyAdvance = 2000
)

var (
	// ErrInvalidSenderKey is returned for malformed sender key material.
	ErrInvalidSenderKey = errors.New("signal: invalid sender key message")
	// ErrSenderKeyTooFar is returned when an iteration is beyond the bound.
	ErrSenderKeyTooFar = errors.New("signal: sender key iteration too far ahead")
)

// SenderKeyDistribution is one member's group key material.
type SenderKeyDistribution struct {
	Version    byte
	ID         uint32
	Iteration  uint32
	ChainKey   [KeySize]byte
	SigningKey [KeySize]byte
}

// ParseSenderKeyDistribution decodes the axolotlSenderKeyDistributionMessage
// bytes carried by Message.senderKeyDistributionMessage.
func ParseSenderKeyDistribution(raw []byte) (*SenderKeyDistribution, error) {
	version, body, err := splitVersion(raw)
	if err != nil {
		return nil, err
	}
	fields, err := parseProtoFields(body)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidSenderKey, err)
	}
	out := &SenderKeyDistribution{Version: version}
	out.ID, err = fields.uint32Field(1)
	if err != nil {
		return nil, err
	}
	out.Iteration, err = fields.uint32Field(2)
	if err != nil {
		return nil, err
	}
	chain, err := fields.bytesField(3)
	if err != nil {
		return nil, err
	}
	if len(chain) != KeySize {
		return nil, fmt.Errorf("%w: chain key is %d bytes, want %d", ErrInvalidSenderKey, len(chain), KeySize)
	}
	copy(out.ChainKey[:], chain)
	signing, err := fields.bytesField(4)
	if err != nil {
		return nil, err
	}
	pub, err := parseCurveKey(signing)
	if err != nil {
		return nil, err
	}
	out.SigningKey = pub
	return out, nil
}

// SenderKeyMessage is one encrypted group message plus its signature.
type SenderKeyMessage struct {
	Version    byte
	ID         uint32
	Iteration  uint32
	Ciphertext []byte
	Signature  []byte
	// Signed is version || protobuf body: the bytes the signature covers.
	Signed []byte
}

// ParseSenderKeyMessage decodes the bytes inside an <enc type="skmsg"> child.
func ParseSenderKeyMessage(raw []byte) (*SenderKeyMessage, error) {
	if len(raw) <= 1+SenderKeySignatureSize {
		return nil, fmt.Errorf("%w: %d bytes", ErrInvalidSenderKey, len(raw))
	}
	version, body, err := splitVersion(raw[:len(raw)-SenderKeySignatureSize])
	if err != nil {
		return nil, err
	}
	signature := append([]byte(nil), raw[len(raw)-SenderKeySignatureSize:]...)
	fields, err := parseProtoFields(body)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidSenderKey, err)
	}
	out := &SenderKeyMessage{Version: version, Signature: signature, Signed: append([]byte(nil), raw[:len(raw)-SenderKeySignatureSize]...)}
	out.ID, err = fields.uint32Field(1)
	if err != nil {
		return nil, err
	}
	out.Iteration, err = fields.uint32Field(2)
	if err != nil {
		return nil, err
	}
	ciphertext, err := fields.bytesField(3)
	if err != nil {
		return nil, err
	}
	if len(ciphertext) == 0 {
		return nil, fmt.Errorf("%w: empty ciphertext", ErrInvalidSenderKey)
	}
	out.Ciphertext = ciphertext
	return out, nil
}

// Verify checks the message signature under the sender's signing key.
func (m *SenderKeyMessage) Verify(signingKey [KeySize]byte) error {
	if m == nil || len(m.Signature) != SenderKeySignatureSize {
		return fmt.Errorf("%w: missing signature", ErrInvalidSenderKey)
	}
	if err := xeddsa.Verify(signingKey, m.Signed, m.Signature); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidSenderKey, err)
	}
	return nil
}

// Decrypt opens the message with a derived message key.
func (m *SenderKeyMessage) Decrypt(iv [16]byte, cipherKey [KeySize]byte) ([]byte, error) {
	plaintext, err := cbc.Decrypt(cipherKey[:], iv[:], m.Ciphertext)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidSenderKey, err)
	}
	return plaintext, nil
}

// SenderChain is one position in a sender's key chain.
type SenderChain struct {
	Iteration uint32
	Key       [KeySize]byte
}

// MessageKey derives the iv and cipher key for the chain's current iteration.
// The chain is not advanced; call Next for that.
func (c SenderChain) MessageKey() (iv [16]byte, cipherKey [KeySize]byte, err error) {
	seed := chainMac(c.Key, SenderKeyMessageSeed)
	raw, err := hkdf.Key(sha256.New, seed[:], nil, SenderKeyInfo, 16+KeySize)
	if err != nil {
		return iv, cipherKey, fmt.Errorf("%w: hkdf: %w", ErrInvalidSenderKey, err)
	}
	copy(iv[:], raw[:16])
	copy(cipherKey[:], raw[16:])
	return iv, cipherKey, nil
}

// Next returns the chain at iteration+1.
func (c SenderChain) Next() SenderChain {
	return SenderChain{Iteration: c.Iteration + 1, Key: chainMac(c.Key, SenderKeyChainSeed)}
}

// Advance moves the chain to target, refusing a jump past MaxSenderKeyAdvance.
func (c SenderChain) Advance(target uint32) (SenderChain, error) {
	if target < c.Iteration {
		return c, fmt.Errorf("%w: stored iteration %d is past %d", ErrInvalidSenderKey, c.Iteration, target)
	}
	if target-c.Iteration > MaxSenderKeyAdvance {
		return c, fmt.Errorf("%w: %d iterations", ErrSenderKeyTooFar, target-c.Iteration)
	}
	for c.Iteration < target {
		c = c.Next()
	}
	return c, nil
}

// chainMac is HMAC-SHA256(chainKey, seed byte), libsignal's getDerivative.
func chainMac(key [KeySize]byte, seed byte) [KeySize]byte {
	mac := hmac.New(sha256.New, key[:])
	mac.Write([]byte{seed})
	var out [KeySize]byte
	copy(out[:], mac.Sum(nil))
	return out
}

// splitVersion reads the version nibble the libsignal serializer prepends.
func splitVersion(raw []byte) (byte, []byte, error) {
	if len(raw) < 2 {
		return 0, nil, fmt.Errorf("%w: %d bytes", ErrInvalidSenderKey, len(raw))
	}
	version := raw[0] >> 4
	if version == 0 {
		return 0, nil, fmt.Errorf("%w: version 0", ErrInvalidSenderKey)
	}
	if version > 3 {
		return 0, nil, fmt.Errorf("%w: version %d", ErrInvalidSenderKey, version)
	}
	return version, raw[1:], nil
}

// parseCurveKey reads a serialized curve key: one type byte (0x05, PF-062)
// followed by the 32-byte Montgomery key.
func parseCurveKey(raw []byte) ([KeySize]byte, error) {
	var out [KeySize]byte
	if len(raw) != KeySize+1 || raw[0] != PublicKeyType {
		return out, fmt.Errorf("%w: signing key is %d bytes with type %#x", ErrInvalidSenderKey, len(raw), firstByte(raw))
	}
	copy(out[:], raw[1:])
	return out, nil
}

func firstByte(raw []byte) byte {
	if len(raw) == 0 {
		return 0
	}
	return raw[0]
}

// protoFields is the minimal protobuf reader sender-key messages need: a few
// varints and length-delimited bytes, nothing else. It refuses duplicate
// fields rather than letting the last one silently win.
type protoFields map[int][][]byte

const (
	wireVarint = 0
	wireBytes  = 2
)

func parseProtoFields(raw []byte) (protoFields, error) {
	fields := protoFields{}
	for pos := 0; pos < len(raw); {
		key, n := readVarint(raw[pos:])
		if n == 0 {
			return nil, fmt.Errorf("truncated field key")
		}
		pos += n
		field := int(key >> 3)
		wire := int(key & 0x7)
		if field == 0 {
			return nil, fmt.Errorf("field number 0")
		}
		switch wire {
		case wireVarint:
			value, n := readVarint(raw[pos:])
			if n == 0 {
				return nil, fmt.Errorf("truncated varint")
			}
			pos += n
			var buf [10]byte
			length := putVarint(buf[:], value)
			fields[field] = append(fields[field], buf[:length])
		case wireBytes:
			length, n := readVarint(raw[pos:])
			if n == 0 {
				return nil, fmt.Errorf("truncated length")
			}
			pos += n
			if length > uint64(len(raw)-pos) {
				return nil, fmt.Errorf("length %d exceeds remaining %d", length, len(raw)-pos)
			}
			fields[field] = append(fields[field], append([]byte(nil), raw[pos:pos+int(length)]...))
			pos += int(length)
		default:
			return nil, fmt.Errorf("unsupported wire type %d", wire)
		}
	}
	return fields, nil
}

func (f protoFields) uint32Field(field int) (uint32, error) {
	values := f[field]
	if len(values) == 0 {
		return 0, fmt.Errorf("%w: missing field %d", ErrInvalidSenderKey, field)
	}
	if len(values) > 1 {
		return 0, fmt.Errorf("%w: repeated field %d", ErrInvalidSenderKey, field)
	}
	value, n := readVarint(values[0])
	if n != len(values[0]) || value > 0xffffffff {
		return 0, fmt.Errorf("%w: bad varint in field %d", ErrInvalidSenderKey, field)
	}
	return uint32(value), nil
}

func (f protoFields) bytesField(field int) ([]byte, error) {
	values := f[field]
	if len(values) == 0 {
		return nil, fmt.Errorf("%w: missing field %d", ErrInvalidSenderKey, field)
	}
	if len(values) > 1 {
		return nil, fmt.Errorf("%w: repeated field %d", ErrInvalidSenderKey, field)
	}
	return values[0], nil
}

// readVarint decodes one base-128 varint; n is 0 on truncation.
func readVarint(raw []byte) (uint64, int) {
	var value uint64
	for i := 0; i < len(raw) && i < 10; i++ {
		b := raw[i]
		value |= uint64(b&0x7f) << (7 * i)
		if b < 0x80 {
			return value, i + 1
		}
	}
	return 0, 0
}

// putVarint encodes a varint into buf and returns its length.
func putVarint(buf []byte, value uint64) int {
	n := 0
	for value >= 0x80 {
		buf[n] = byte(value) | 0x80
		value >>= 7
		n++
	}
	buf[n] = byte(value)
	return n + 1
}
